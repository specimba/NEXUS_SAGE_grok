from PIL import Image, ImageDraw, ImageFont
img = Image.new("RGB", (1200, 630), "#07090c")
d = ImageDraw.Draw(img)
d.rectangle([48,48,1152,582], outline="#4a3400", width=2)
d.rectangle([56,56,1144,574], outline="#2a1c00", width=1)
d.line([(48,72),(48,48),(72,48)], fill="#ffb000", width=2)
d.line([(1152,72),(1152,48),(1128,48)], fill="#ffb000", width=2)
d.line([(48,558),(48,582),(72,582)], fill="#ffb000", width=2)
d.line([(1152,558),(1152,582),(1128,582)], fill="#ffb000", width=2)
font_lg = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf", 96)
font_md = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", 28)
font_sm = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", 22)
font_xs = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", 16)
def center(text, y, font, fill):
    bbox = d.textbbox((0,0), text, font=font)
    w = bbox[2]-bbox[0]
    d.text(((1200-w)/2, y), text, font=font, fill=fill)
center("NEXUS · CYCLE 003", 190, font_sm, "#6b4a00")
center("SAGE", 250, font_lg, "#ffb000")
center("//DESK", 360, font_md, "#ffd47a")
cx, cy = 600, 470
d.polygon([(cx-28,cy+4),(cx,cy-28),(cx+28,cy+4)], fill="#ffb000")
d.rectangle([cx-4,cy-20,cx+4,cy+4], fill="#6b4a00")
d.rectangle([cx-8,cy+4,cx+8,cy+20], fill="#2a1c00")
d.rectangle([cx-16,cy+20,cx+16,cy+26], fill="#4a3400")
center("FALLOUT x MATRIX · AMBER PRIMARY · SIGNAL GREEN ONLY", 540, font_xs, "#6b4a00")
img.save("desk/public/og.png", "PNG")
img.save("desk/public/og.jpg", "JPEG", quality=92)
print("ok", img.size)
