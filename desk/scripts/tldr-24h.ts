#!/usr/bin/env bun
/**
 * PASS-F2.2 — Past-24h TL;DR step. Called by scripts/rank-snapshot.ts every crawl (after the Wire); also runnable alone:
 *   bun scripts/tldr-24h.ts [--desk <dir>]
 * Reads the crawl's data modules (same publishers / members / scores / taste inputs as the Wire), writes
 * src/data/tldr-24h.ts only when its bytes change. Deterministic: a pure function of the crawl modules.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { PULSE_CLUSTERS, PULSE_CLUSTERS_AT } from "@/data/pulse-clusters";
import { GNEWS_RSS } from "@/data/gnews-rss";
import { HN_PULSE } from "@/data/hn-pulse";
import { RSS_LABS } from "@/data/rss-labs";
import { RSS_SECURITY } from "@/data/rss-security";
import { RSS_ANALYST } from "@/data/rss-analyst";
import { RELEASES_ATOM } from "@/data/releases-atom";
import { X_TASTE } from "@/data/x-taste";
import { memberInfo } from "@/lib/member-info";
import { istanbulDate } from "@/lib/lead-pick";
import { buildTldr, type Tldr } from "@/lib/tldr-24h";
import { plainHeadline } from "@/lib/plain-headline";

export function computeTldr(excludeIds: string[] = []): Tldr {
  const publishers: Record<string, string> = {};
  for (const g of GNEWS_RSS) if (g.publisher) publishers[g.id] = g.publisher;
  for (const r of RSS_LABS) publishers[r.id] = r.lab;
  for (const r of RSS_SECURITY) publishers[r.id] = r.lab;
  for (const a of RSS_ANALYST) publishers[a.id] = a.feed;
  for (const r of RELEASES_ATOM) publishers[r.id] = "github.com";
  const scores: Record<string, number> = {};
  for (const h of HN_PULSE) scores[h.id] = h.score;
  const t = buildTldr(PULSE_CLUSTERS, {
    crawlAt: PULSE_CLUSTERS_AT,
    date: istanbulDate(PULSE_CLUSTERS_AT),
    publishers,
    members: memberInfo(),
    scores,
    // PASS-U U3: every member's own time, so bullets carry the story's first-publish time.
    memberAt: Object.fromEntries(Object.entries(memberInfo()).flatMap(([id, m]) => (m.at ? [[id, m.at]] : []))),
    tasteIds: X_TASTE.items.map((t) => t.id),
    // PASS-WIRE-CLUSTER (4): the lead plate's story never repeats as a Brief bullet.
    excludeIds,
  });
  // PASS-F2.3a: plain publisher headline (cleaned, never reworded).
  return { ...t, bullets: t.bullets.map((b) => ({ ...b, title: plainHeadline(b.title) })) };
}

export function renderTldrModule(t: Tldr): string {
  return `/** PASS-F2.2 Past-24h TL;DR — generated by scripts/tldr-24h.ts (rank-snapshot step). Extractive: Wire-gated rows only. */
import type { Tldr } from "@/lib/tldr-24h";

export const TLDR_24H: Tldr = ${JSON.stringify(t, null, 2)};
`;
}

export function writeTldr(desk: string, excludeIds: string[] = []): string {
  const t = computeTldr(excludeIds);
  const p = resolve(desk, "src/data/tldr-24h.ts");
  const body = renderTldrModule(t);
  const same = existsSync(p) && readFileSync(p, "utf8") === body;
  if (!same) writeFileSync(p, body);
  return `tldr OK ${t.bullets.length} bullets${t.quiet ? " · quiet day" : ""} · crawl ${t.crawl_at} · ${same ? "unchanged" : "wrote"} src/data/tldr-24h.ts`;
}

if (import.meta.main) {
  const i = process.argv.indexOf("--desk");
  console.log(writeTldr(resolve(i > 0 ? process.argv[i + 1]! : resolve(import.meta.dir, ".."))));
}
